/** Real DSH pages exercise credential reveal, dated checks and confirmed management operations. */
import assert from 'node:assert/strict'
import { resolve } from 'node:path'
import { expect as baseExpect } from '@playwright/test'
const expect = baseExpect.configure({ timeout: 30000 })

/** Verify server editing and connection state with a deterministic CPU transport failure. */
export async function checkServerManagement(page, control, output) {
  const card = () => page.locator('article[data-server-id]').filter({ has: page.getByRole('heading', { name: 'CPU A', exact: true }) })
  const password = () => page.getByRole('dialog').getByLabel(/^(服务器密码|Server password)$/)
  await card().getByRole('button', { name: /^(编辑|Edit)$/ }).click()
  await expect(password()).toHaveValue('')
  await expect(password()).toHaveAttribute('type', 'password')
  await expect(password()).toHaveAttribute('placeholder', '••••••••')
  await page.getByRole('button', { name: /^(显示密码|Show password)$/ }).click()
  await expect(password()).toHaveValue('test-fixture-password')
  await page.getByRole('button', { name: /^(隐藏密码|Hide password)$/ }).click()
  await expect(password()).toHaveValue('')
  await password().fill('discarded-edit')
  await page.getByRole('button', { name: /^(显示密码|Show password)$/ }).click()
  await expect(password()).toHaveValue('discarded-edit')
  await page.keyboard.press('Escape')
  await card().getByRole('button', { name: /^(编辑|Edit)$/ }).click()
  await expect(password()).toHaveValue('')
  await page.getByRole('button', { name: /^(显示密码|Show password)$/ }).click()
  await expect(password()).toHaveValue('test-fixture-password')
  await page.keyboard.press('Escape')
  assert.ok(!(await page.locator('body').innerText()).includes('test-fixture-password'))
  await control('fail-connection')
  await card().getByRole('button', { name: /^(检查连接|Check connection)$/ }).click()
  await expect(card().getByText(/^(检查失败|Check failed)$/)).toBeVisible()
  await expect(card().getByText(/^(检查通过|Check passed)$/)).toHaveCount(0)
  await card().locator('summary').filter({ hasText: /上次检测结果|Last successful result/ }).click()
  await expect(card().getByText('CPU test provider', { exact: true })).toBeVisible()
  await page.screenshot({ path: resolve(output, 'management-server-failed-history.png'), fullPage: true, animations: 'disabled' })
  await page.reload()
  await page.getByRole('button', { name: /^(服务器|Servers)$/ }).click()
  await expect(card().getByText(/^(检查失败|Check failed)$/)).toBeVisible()
  await control('restore-connection')
  await card().getByRole('button', { name: /^(检查连接|Check connection)$/ }).click()
  await expect(card().getByText(/^(检查通过|Check passed)$/)).toBeVisible()
  await page.getByRole('button', { name: /^(新建实验|New experiment)$/ }).click()
  await page.getByRole('checkbox', { name: 'CPU A', exact: true }).check()
  const coordinator = page.getByRole('button', { name: /^(本次实验调度主机|Experiment coordinator)$/ })
  await expect(coordinator).toContainText('CPU A')
  await expect(coordinator).toBeDisabled()
  await page.getByRole('checkbox', { name: 'CPU B', exact: true }).check()
  await coordinator.click()
  await page.getByRole('menuitem', { name: 'CPU B', exact: true }).click()
  await expect(coordinator).toContainText('CPU B')
  await page.getByRole('checkbox', { name: 'CPU B', exact: true }).uncheck()
  await expect(coordinator).toContainText('CPU A')
  await page.getByRole('checkbox', { name: 'CPU A', exact: true }).uncheck()
  await expect(page.getByRole('button', { name: /^(提交实验|Submit experiment)$/ })).toBeDisabled()
  return { passwordRevealAndCancel: true, failedCheckRetainsDatedHardware: true, coordinatorSelection: true }
}

/** Verify layout, remote-cleanup failures, record-only recovery and late snapshot exclusion. */
export async function checkExperimentManagement(page, control, output) {
  await page.getByRole('button', { name: /^(实验|Experiments)$/ }).click()
  await page.getByRole('button', { name: /^(全部实验|All experiments)$/ }).click()
  const before = await control()
  const row = before.experiments.find(value => value.request.objective === 'CPU failure experiment')
  assert.ok(row)
  const tableRow = () => page.locator(`tr[data-experiment-id="${row.request.experimentId}"]`)
  await expect(tableRow()).toBeVisible()
  const failureTag = tableRow().getByText(/^(失败|Failed)$/, { exact: true })
  await expect(failureTag).toBeVisible()
  const normalColor = await tableRow().locator('time').evaluate(el => getComputedStyle(el).color)
  assert.notEqual(await failureTag.evaluate(el => getComputedStyle(el).color), normalColor)
  const columnWidths = await page.locator('table thead th').evaluateAll(cells => cells.map(cell => cell.getBoundingClientRect().width))
  assert.ok(columnWidths[4] >= 100, 'Server column remains readable with the official sidebar open')
  await page.screenshot({ path: resolve(output, 'management-experiments-light.png'), fullPage: true, animations: 'disabled' })
  await page.evaluate(() => { document.body.dataset.dsDarkTheme = '' })
  await page.screenshot({ path: resolve(output, 'management-experiments-dark.png'), fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 900, height: 720 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await page.screenshot({ path: resolve(output, 'management-experiments-narrow.png'), fullPage: true, animations: 'disabled' })
  await page.evaluate(() => { delete document.body.dataset.dsDarkTheme })
  await page.setViewportSize({ width: 1280, height: 720 })
  await tableRow().getByRole('button', { name: /更多操作|More actions/ }).click()
  await page.getByRole('menuitem', { name: /^(删除实验|Delete experiment)$/ }).click()
  const dialog = () => page.getByRole('dialog')
  const cleanup = () => dialog().getByRole('checkbox', { name: /同时清理远端文件|Also clean up remote files/ })
  await expect(cleanup()).not.toBeChecked()
  await cleanup().check()
  await expect(dialog()).toContainText(row.preparation.placements[0].runRoot)
  await page.screenshot({ path: resolve(output, 'management-delete-confirm.png'), fullPage: true, animations: 'disabled' })
  await control('fail-cleanup')
  await dialog().getByRole('button', { name: /^(删除并清理文件|Delete and clean up files)$/ }).click()
  await expect(dialog().getByText(/删除未完成|Deletion incomplete/).first()).toBeVisible()
  assert.ok((await control()).experiments.some(value => value.request.experimentId === row.request.experimentId))
  await cleanup().uncheck()
  await dialog().getByRole('button', { name: /^(删除记录|Delete records)$/ }).click()
  await expect(dialog()).toHaveCount(0)
  await expect(tableRow()).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: /^(实验|Experiments)$/ }).click()
  await expect(tableRow()).toHaveCount(0)
  const after = await control()
  assert.ok(after.deletedIds.includes(row.request.experimentId))
  await control('restore-cleanup')
  const ended = after.experiments.find(value => value.request.objective === 'CPU operator question')
  const endedRow = page.locator(`tr[data-experiment-id="${ended.request.experimentId}"]`)
  await endedRow.getByRole('checkbox').check()
  await page.getByRole('button', { name: /^(删除所选|Delete selected)$/ }).click()
  await cleanup().check()
  await dialog().getByRole('button', { name: /^(删除并清理文件|Delete and clean up files)$/ }).click()
  await expect(dialog()).toHaveCount(0)
  await expect(endedRow).toHaveCount(0)
  assert.ok((await control()).cleanupCalls.some(call => call.experimentId === ended.request.experimentId))
  return { layoutA: true, recordOnlyAfterCleanupFailure: true, survivesReload: true, batchOwnedCleanup: true }
}
